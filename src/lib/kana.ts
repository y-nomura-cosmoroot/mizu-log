/** 濁点・半濁点付きカナ→無印カナの対応表(OCRでの濁点誤認識対策に使う) */
const DAKUTEN_MAP: Record<string, string> = {
  ガ: "カ", ギ: "キ", グ: "ク", ゲ: "ケ", ゴ: "コ",
  ザ: "サ", ジ: "シ", ズ: "ス", ゼ: "セ", ゾ: "ソ",
  ダ: "タ", ヂ: "チ", ヅ: "ツ", デ: "テ", ド: "ト",
  バ: "ハ", ビ: "ヒ", ブ: "フ", ベ: "ヘ", ボ: "ホ",
  パ: "ハ", ピ: "ヒ", プ: "フ", ペ: "ヘ", ポ: "ホ",
  ヴ: "ウ",
  が: "か", ぎ: "き", ぐ: "く", げ: "け", ご: "こ",
  ざ: "さ", じ: "し", ず: "す", ぜ: "せ", ぞ: "そ",
  だ: "た", ぢ: "ち", づ: "つ", で: "て", ど: "と",
  ば: "は", び: "ひ", ぶ: "ふ", べ: "へ", ぼ: "ほ",
  ぱ: "は", ぴ: "ひ", ぷ: "ふ", ぺ: "へ", ぽ: "ほ",
};

/**
 * カタカナ・ひらがなの濁点/半濁点を取り除いた形に正規化する。
 * OCRは濁点・半濁点(小さい記号)を見落とし/誤付与しやすく(例: パ→バ)、
 * この正規化で「濁点/半濁点の違いだけ」の表記ゆれを同一視できる。
 */
export function stripDakuten(s: string): string {
  return [...s].map((c) => DAKUTEN_MAP[c] ?? c).join("");
}
